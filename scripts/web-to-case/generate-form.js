#!/usr/bin/env node
/**
 * Generates a Web-to-Case request form for one community of the connected org.
 *
 *   node scripts/web-to-case/generate-form.js [communityCode] [targetOrg]
 *   e.g. node scripts/web-to-case/generate-form.js GVR sd
 *
 * Writes web-to-case/<code>-request-form.html (git-ignored: it contains this org's IDs).
 * Web-to-Case cannot fill lookup fields, so the form sends text (community code, unit number,
 * category name) and the "Case - Before Save" flow turns it into the Community/Unit/Category lookups.
 */
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const communityCode = (process.argv[2] || "GVR").toUpperCase();
const targetOrg = process.argv[3] || "sd";

function sf(args) {
  const out = execSync(`sf ${args} --target-org ${targetOrg} --json`, {
    encoding: "utf8",
    env: { ...process.env, SF_DISABLE_PROGRESS_BAR: "true" }
  });
  return JSON.parse(out).result;
}
const query = (soql, tooling = false) =>
  sf(`data query ${tooling ? "--use-tooling-api " : ""}--query "${soql}"`)
    .records;
const escapeHtml = (s) =>
  String(s).replace(
    /[&<>"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]
  );

const orgId = query("SELECT Id FROM Organization")[0].Id.slice(0, 15);
const fieldIds = Object.fromEntries(
  query(
    "SELECT Id, DeveloperName FROM CustomField WHERE TableEnumOrId = 'Case' AND DeveloperName IN ('Community_Code', 'Web_Category', 'Web_Unit_Number')",
    true
  ).map((f) => [f.DeveloperName, f.Id.slice(0, 15)])
);
const community = query(
  `SELECT Name, Organisation_Type__c FROM Community__c WHERE Community_Code__c = '${communityCode}'`
)[0];
if (!community) {
  throw new Error(`No community with code ${communityCode}`);
}
const categories = query(
  `SELECT Name FROM Service_Category__c WHERE Active__c = true AND Organisation_Type__c = '${community.Organisation_Type__c}' ORDER BY Name`
).map((c) => c.Name);
const unitLabel =
  community.Organisation_Type__c === "Business"
    ? "Customer number (e.g. CUST-1001)"
    : "Flat / unit number (e.g. B-102)";

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(community.Name)} - Raise a request</title>
  <style>
    body { font-family: system-ui, sans-serif; background: #f4f6f9; margin: 0; padding: 2rem 1rem; color: #181818; }
    form { max-width: 34rem; margin: 0 auto; background: #fff; padding: 1.5rem 2rem; border-radius: 0.5rem; box-shadow: 0 1px 4px rgba(0,0,0,.1); }
    h1 { font-size: 1.4rem; margin: 0 0 .25rem; }
    p.hint { color: #555; margin-top: 0; }
    label { display: block; font-weight: 600; margin-top: 1rem; }
    input, select, textarea { width: 100%; box-sizing: border-box; padding: .5rem; margin-top: .25rem; border: 1px solid #c9c9c9; border-radius: .25rem; font: inherit; }
    button { margin-top: 1.5rem; background: #0b5cab; color: #fff; border: 0; padding: .65rem 1.25rem; border-radius: .25rem; font: inherit; cursor: pointer; }
  </style>
</head>
<body>
  <!-- Generated by scripts/web-to-case/generate-form.js for org ${orgId}. -->
  <form action="https://webto.salesforce.com/servlet/servlet.WebToCase?encoding=UTF-8&amp;orgId=${orgId}" method="POST">
    <h1>${escapeHtml(community.Name)}</h1>
    <p class="hint">Raise a service request. You will get an email with your case number.</p>

    <input type="hidden" name="orgid" value="${orgId}">
    <input type="hidden" name="retURL" value="https://example.com/request-received">
    <input type="hidden" name="${fieldIds.Community_Code}" value="${communityCode}">

    <label for="name">Your name</label>
    <input id="name" name="name" maxlength="80" required>

    <label for="email">Email</label>
    <input id="email" name="email" type="email" maxlength="80" required>

    <label for="phone">Phone</label>
    <input id="phone" name="phone" maxlength="40">

    <label for="unit">${unitLabel}</label>
    <input id="unit" name="${fieldIds.Web_Unit_Number}" maxlength="20" required>

    <label for="category">What is it about?</label>
    <select id="category" name="${fieldIds.Web_Category}" required>
      <option value="">Choose a category</option>
${categories.map((c) => `      <option value="${escapeHtml(c)}">${escapeHtml(c)}</option>`).join("\n")}
    </select>

    <label for="subject">Subject</label>
    <input id="subject" name="subject" maxlength="80" required>

    <label for="description">Details</label>
    <textarea id="description" name="description" rows="5"></textarea>

    <button type="submit">Submit request</button>
  </form>
</body>
</html>
`;

const outDir = path.join(__dirname, "..", "..", "web-to-case");
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(
  outDir,
  `${communityCode.toLowerCase()}-request-form.html`
);
fs.writeFileSync(outFile, html);
console.log(
  `Wrote ${outFile} (${categories.length} categories, fields ${JSON.stringify(fieldIds)})`
);
